-- Baseline schema for the model as it exists today (accounts, profiles, task menus, bookings).
--
-- Column sizes match the Bean Validation limits on the request DTOs, so anything the API
-- accepts also fits in the database. Enum-valued columns are guarded by CHECK constraints:
-- adding an enum value therefore needs a new migration that replaces the constraint.

CREATE TABLE users (
    user_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(255) NOT NULL,
    password     VARCHAR(255) NOT NULL,
    account_type VARCHAR(20)  NOT NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT users_account_type_check CHECK (account_type IN ('STUDENT', 'MENTOR'))
);

CREATE TABLE students (
    student_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL,
    first_name       VARCHAR(100),
    last_name        VARCHAR(100),
    bio              VARCHAR(2000),
    major            VARCHAR(100),
    graduation_year  INTEGER,
    career_interests VARCHAR(1000),
    CONSTRAINT uq_students_user UNIQUE (user_id),
    CONSTRAINT fk_students_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE TABLE mentors (
    mentor_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    first_name VARCHAR(100),
    last_name  VARCHAR(100),
    bio        VARCHAR(2000),
    role_title VARCHAR(100),
    company    VARCHAR(100),
    yrs_exp    VARCHAR(50),
    industries VARCHAR(1000),
    expertise  VARCHAR(1000),
    photo_url  VARCHAR(500),
    CONSTRAINT uq_mentors_user UNIQUE (user_id),
    CONSTRAINT fk_mentors_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE TABLE tasks (
    task_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id   BIGINT       NOT NULL,
    title       VARCHAR(200) NOT NULL,
    description VARCHAR(2000),
    duration    INTEGER      NOT NULL,
    category    VARCHAR(30)  NOT NULL,
    CONSTRAINT fk_tasks_mentor FOREIGN KEY (mentor_id) REFERENCES mentors (mentor_id) ON DELETE CASCADE,
    CONSTRAINT tasks_category_check CHECK (category IN ('RESUME_REVIEW', 'MOCK_INTERVIEW', 'CAREER_ADVICE'))
);

CREATE TABLE bookings (
    booking_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    BIGINT      NOT NULL,
    mentor_id     BIGINT      NOT NULL,
    task_id       BIGINT      NOT NULL,
    proposed_date TIMESTAMP   NOT NULL,
    status        VARCHAR(20) NOT NULL,
    student_msg   VARCHAR(1000),
    mentor_resp   VARCHAR(1000),
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_bookings_student FOREIGN KEY (student_id) REFERENCES students (student_id) ON DELETE CASCADE,
    CONSTRAINT fk_bookings_mentor  FOREIGN KEY (mentor_id)  REFERENCES mentors (mentor_id)  ON DELETE CASCADE,
    -- No cascade: a task that has bookings cannot be silently deleted along with them.
    CONSTRAINT fk_bookings_task    FOREIGN KEY (task_id)    REFERENCES tasks (task_id),
    CONSTRAINT bookings_status_check CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'COMPLETED', 'CANCELLED'))
);

-- PostgreSQL does not index foreign keys automatically.
CREATE INDEX idx_tasks_mentor_id         ON tasks (mentor_id);
CREATE INDEX idx_bookings_student_id     ON bookings (student_id);
CREATE INDEX idx_bookings_mentor_status  ON bookings (mentor_id, status);
CREATE INDEX idx_bookings_task_id        ON bookings (task_id);
